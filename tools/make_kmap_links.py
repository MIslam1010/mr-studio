#!/usr/bin/env python3
"""Generate the Knowledge Map <-> MR Studio link table.

Reads the map's node data (``<kmap>/kmap-data/a_*.js``, read only), takes each node's Modern Robotics reference
(``references[].book == "MR"``, section from ``§x.y``), maps the section to an MR Studio tab with
``mrstudio.kmap_links.SECTION_TABS`` and writes

* ``mrstudio/data/kmap/mrstudio_targets.json`` -- used by the theory-panel footers and by the map build;
* ``docs/KMAP-LINKING.md`` -- the contract for the map build (format, URL scheme, fallback, Electron handler).

Node titles (labels) come from the map page (``Robotics Knowledge Map.html``) when it is there.

Usage:  python tools/make_kmap_links.py [--kmap DIR] [--out JSON] [--doc MD]
"""
from __future__ import annotations

import argparse
import datetime as _dt
import glob
import json
import os
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from mrstudio import kmap_links as kl  # noqa: E402

VERSION = 1


def _long_names() -> dict[str, str]:
    try:
        from mrstudio.gui.app import TAB_LONG_NAMES
        names = dict(TAB_LONG_NAMES)
    except Exception:  # noqa: BLE001 - Qt missing etc.: fall back to the class names
        names = {}
    for k, v in kl._EXTRA_LONG_NAMES.items():
        names.setdefault(k, v)
    return {c: names.get(c, c) for c in kl.TAB_ORDER}


def read_nodes(kmap: Path) -> dict[str, dict]:
    """node id -> node dict from every ``a_*.js`` (JSON after the first ``{``)."""
    nodes: dict[str, dict] = {}
    files = sorted(glob.glob(str(kmap / "kmap-data" / "a_*.js")))
    if not files:
        raise SystemExit(f"no kmap-data/a_*.js under {kmap}")
    for f in files:
        s = Path(f).read_text(encoding="utf-8")
        nodes.update(json.loads(s[s.index("{"): s.rindex("}") + 1]))
    return nodes


# leading run of string-valued keys of a JSON object ("id", "parent", "title", "kind", ... in any order)
_FLAT_RE = re.compile(r'\{((?:"[a-z_]+": "(?:[^"\\]|\\.)*", )+)')


def read_titles(kmap: Path) -> dict[str, str]:
    """node id -> title, from the map page's embedded tree (empty if the page is missing)."""
    for name in ("Robotics Knowledge Map.html", "Robotics Knowledge Map - Student Edition/index.html"):
        p = kmap / name
        if p.is_file():
            s = p.read_text(encoding="utf-8", errors="replace")
            out = {}
            for m in _FLAT_RE.finditer(s):
                try:
                    d = json.loads("{" + m.group(1).rstrip(", ") + "}")
                except ValueError:
                    continue
                if "id" in d and "title" in d and d["id"].count(".") >= 2:
                    out.setdefault(d["id"], d["title"])
            return out
    return {}


def build(kmap: Path) -> dict:
    nodes, titles = read_nodes(kmap), read_titles(kmap)
    out: dict[str, dict] = {}
    for nid in sorted(nodes):
        for ref in nodes[nid].get("references", []):
            if ref.get("book") != "MR":
                continue
            sec = kl.mr_section(ref.get("where", ""))
            hit = kl.tab_for_section(sec) if sec else None
            if not hit:
                continue
            tab, robot, preset = hit
            out[nid] = {"tab": tab, "robot": robot, "preset": preset, "label": titles.get(nid, nid), "mr": sec,
                        "url": kl.launch_url(tab, robot, preset)}
            break
    tabs = _long_names()
    return {
        "version": VERSION,
        "generated": _dt.datetime.now(_dt.timezone.utc).replace(microsecond=0).isoformat(),
        "scheme": kl.SCHEME_TEMPLATE,
        "tab_index_base": 0,
        "tabs": {c: {"index": i, "long_name": tabs[c]} for i, c in enumerate(kl.TAB_ORDER)},
        "nodes": out,
    }


DOC = """# Knowledge Map ↔ MR Studio linking

Generated by `tools/make_kmap_links.py` on {generated}. Do not edit by hand: change
`mrstudio/kmap_links.py` (`SECTION_TABS`) and run

```bash
.venv/bin/python tools/make_kmap_links.py          # reads <Knowledge Map>/kmap-data/a_*.js (read only)
```

## 1. MR Studio → map (theory-panel footers)

Every tab's theory panel ends with a **Knowledge Map** heading and up to {footer_max} links to map nodes about
the tab (`kmap_links.theory_footer`, appended in `BaseTab.assemble`). A link is

```
<map page>#map/<node id>/learn
```

where `<map page>` is, in this order: the environment variable `MRSTUDIO_KMAP_URL`; the local student edition
`<Knowledge Map>/Robotics Knowledge Map - Student Edition/index.html` (folder: `MRSTUDIO_KMAP_DIR`, default
`~/Documents/Edu/Lectures/Robotics/Knowledge Map`); else the published artifact {artifact}.
Set `MRSTUDIO_NO_KMAP_LINKS=1` to leave the footers out (e.g. for documentation screenshots).

Note: some browsers / `open` drop the `#fragment` of a `file://` URL handed over by the OS. If the local
edition opens on its start page instead of the node, set `MRSTUDIO_KMAP_URL` to an `http(s)` copy of the map.

## 2. Map → MR Studio (`mrstudio://` URL scheme)

```
{scheme}
```

* `tab` — tab class name (preferred, stable) or 0-based tab index (= MR Studio's `--tab`).
* `robot` — a robot name of MR Studio's robot selector (only for tabs that use it), URL-encoded.
* `preset` — a key of the tab's own preset box (only some tabs), URL-encoded.
* Empty parts are left out. `mrstudio.kmap_links.parse_launch_url` reads the URL; an unknown tab keeps the
  current tab.

The scheme is registered by the installers (macOS `CFBundleURLTypes` in `packaging/mrstudio.spec`, Windows
`[Registry]` in `packaging/mrstudio.iss`); from source, run `python run_app.py --open "<url>"`.

## 3. The data file for the map build

`mrstudio/data/kmap/mrstudio_targets.json` (UTF-8):

```json
{{
  "version": {version},
  "generated": "ISO-8601 UTC time",
  "scheme": "{scheme}",
  "tab_index_base": 0,
  "tabs":  {{"<TabClass>": {{"index": 0, "long_name": "Forward kinematics"}}, ...}},
  "nodes": {{"<node id>": {{"tab": "<TabClass>", "robot": "<name>|null", "preset": "<key>|null",
                          "label": "<node title>", "mr": "<MR section>", "url": "mrstudio://open?..."}}, ...}}
}}
```

A node is in `nodes` only when its Modern Robotics reference maps to a tab; `url` is the ready-made launch URL.
Section → tab rule: longest prefix of the MR section in `SECTION_TABS` (a reference without `§` falls back to its
chapter: "Ch. 12 …", "Example 12.2", "Eq. (8.9)"; appendices are not mapped).

### What the map build does with it (Knowledge Map side)

1. `build_page.py` reads the JSON (path: `KMAP_MRSTUDIO_TARGETS`, default
   `<MR Studio>/mrstudio/data/kmap/mrstudio_targets.json`) and emits `kmap-data/mrstudio.js`; if the file is
   missing it emits nothing and no button appears.
2. A mapped node gets a button **Open in MR Studio** (`<button data-mrs="<node id>">`). Click:
   `location.href = nodes[id].url`, then after 1.5 s a fallback popover:
   *"If MR Studio did not open: download it from the MR Studio releases page, or run
   `python run_app.py --tab <index> --robot "<robot>"` in the MR Studio folder."* (`index` from `tabs[tab].index`).
3. Electron shell (`Robotics Knowledge Map App/main.js`, function `external()`): also hand `mrstudio:` URLs to the OS:

   ```js
   if (/^(https?|mrstudio):/i.test(url)) {{ shell.openExternal(url); }}
   ```

## 4. Current table ({n_nodes} nodes from {n_mr} nodes with an MR reference)

| # | Tab | Long name | Nodes |
|---|---|---|---|
{rows}

Section map (`SECTION_TABS`):

| MR section | Tab | Robot | Preset |
|---|---|---|---|
{sec_rows}
"""


def write_doc(data: dict, n_mr: int, path: Path):
    count = Counter(e["tab"] for e in data["nodes"].values())
    rows = "\n".join(f"| {v['index']} | `{c}` | {v['long_name']} | {count.get(c, 0)} |"
                     for c, v in data["tabs"].items())
    secs = sorted(kl.SECTION_TABS, key=kl._sec_key)
    sec_rows = "\n".join(f"| {s} | `{kl.SECTION_TABS[s][0]}` | {kl.SECTION_TABS[s][1] or '—'} | "
                         f"{kl.SECTION_TABS[s][2] or '—'} |" for s in secs)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(DOC.format(generated=data["generated"][:10], footer_max=kl.FOOTER_MAX, artifact=kl.ARTIFACT_URL,
                               scheme=data["scheme"], version=data["version"], n_nodes=len(data["nodes"]),
                               n_mr=n_mr, rows=rows, sec_rows=sec_rows), encoding="utf-8")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--kmap", default=os.environ.get("MRSTUDIO_KMAP_DIR") or str(kl.KMAP_DIR_DEFAULT))
    ap.add_argument("--out", default=str(kl.TARGETS_JSON))
    ap.add_argument("--doc", default=str(ROOT / "docs" / "KMAP-LINKING.md"))
    a = ap.parse_args(argv)
    kmap = Path(a.kmap)
    data = build(kmap)
    n_mr = sum(any(r.get("book") == "MR" for r in n.get("references", [])) for n in read_nodes(kmap).values())
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(data, ensure_ascii=False, indent=1, sort_keys=False) + "\n", encoding="utf-8")
    write_doc(data, n_mr, Path(a.doc))
    count = Counter(e["tab"] for e in data["nodes"].values())
    print(f"{len(data['nodes'])} of {n_mr} MR-referenced nodes mapped -> {out}")
    for c in kl.TAB_ORDER:
        print(f"  {c:20s} {count.get(c, 0)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
